def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def fmt_duration(seconds: float) -> str:
    seconds = int(seconds)
    h, rest = divmod(seconds, 3600)
    m, s = divmod(rest, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


@dataclass
class Run:
    args: argparse.Namespace
    account: str
    total: int
    state: dict
    acc_state: dict
    islem: Islem
    parallel: int
    interval: float | None  # --hedef-dk: profiller arası ortak aralık (sn)
    counts: dict = field(default_factory=dict)
    processed: int = 0
    succeeded: int = 0
    consecutive_fail: int = 0
    stop_reason: str | None = None
    announced: bool = False
    started: float = field(default_factory=time.monotonic)
    next_slot: float = 0.0
    last_stats: float = field(default_factory=time.monotonic)

    @property
    def stopping(self) -> bool:
        return self.stop_reason is not None

    def rate_per_min(self) -> float:
        elapsed = time.monotonic() - self.started
        return self.processed / elapsed * 60 if elapsed > 0 else 0.0

    def record(self, n: int, username: str, date: str, result: str) -> None:
        self.processed += 1
        self.counts[result] = self.counts.get(result, 0) + 1
        where = f" ({date})" if date else ""
        log(f"[{n}/{self.total}] {username}{where}: {self.islem.labels.get(result, result)}")
        if self.args.dry_run:
            return
        now = datetime.now().isoformat(timespec="seconds")
        if result == self.islem.done:
            self.succeeded += 1
            self.acc_state[self.islem.done][username] = now
            self.acc_state["skipped"].pop(username, None)
            self.consecutive_fail = 0
        elif result in self.islem.final_skips:
            self.acc_state["skipped"][username] = result
            self.consecutive_fail = 0
        else:
            self.acc_state["skipped"][username] = result
            if result == "failed":
                self.consecutive_fail += 1
        save_state(self.state, self.islem.state_path)

    def maybe_stats(self) -> None:
        now = time.monotonic()
        if self.processed % 25 and now - self.last_stats < 60:
            return
        self.last_stats = now
        elapsed = now - self.started
        left = self.total - self.processed
        eta = left / (self.processed / elapsed) if self.processed else 0
        log(
            f"— ilerleme {self.processed}/{self.total} · {self.succeeded} {self.islem.verb} · "
            f"hız {self.rate_per_min():.1f} profil/dk · geçen {fmt_duration(elapsed)} · "
            f"kalan ~{fmt_duration(eta)}"
        )

    async def stop(self, reason: str, page: Page | None = None, username: str = "") -> None:
        """Bütün sekmeleri durdurur ve terminale bir kez rapor basar."""
        if self.announced:
            return
        self.announced = True
        self.stop_reason = reason
        elapsed = time.monotonic() - self.started
        message = ""
        shot = None
        if page is not None:
            text = await body_text(page)
            m = BLOCKED_RE.search(text)
            if m:
                message = re.sub(r"\s+", " ", text[m.start() : m.end() + 120]).strip()
            try:
                LOG_DIR.mkdir(exist_ok=True)
                shot = LOG_DIR / f"engel-{datetime.now():%Y%m%d-%H%M%S}.png"
                await page.screenshot(path=str(shot))
            except PWError:
                shot = None

        bar = "=" * 64
        lines = [
            "",
            bar,
            f"  ⛔ {STOP_TITLES.get(reason, reason)}",
            bar,
            f"  saat            : {datetime.now():%H:%M:%S}",
            f"  son profil      : @{username}" if username else None,
            f"  başlangıçtan    : {fmt_duration(elapsed)} sonra",
            f"  bu çalıştırmada : {self.processed} profil işlendi, {self.succeeded} {self.islem.verb}",
            f"  hız             : {self.rate_per_min():.1f} profil/dk  ({self.parallel} sekme)",
            f"  sayfadaki mesaj : \"{message}\"" if message else None,
            f"  ekran görüntüsü : {rel(shot)}" if shot else None,
            "  İlerleme kaydedildi. Birkaç saat sonra aynı komutla kaldığı yerden devam eder."
            if reason in ("blocked", "silent")
            else "  İlerleme kaydedildi. Tarayıcıyı --headless olmadan açıp durumu kontrol et."
            if reason in ("checkpoint", "logged_out")
            else "  İlerleme kaydedildi.",
            bar,
            "",
        ]
        print("\a" + "\n".join(l for l in lines if l is not None), flush=True)

    async def take_slot(self) -> None:
        """--hedef-dk: sekmeler ortak bir sıradan zaman alır; böylece toplam hız sabit kalır."""
        if not self.interval:
            return
        loop = asyncio.get_running_loop()
        slot = max(loop.time(), self.next_slot)
        self.next_slot = slot + self.interval * random.uniform(0.8, 1.2)
        await self.sleep_until(slot)

    async def sleep_until(self, when: float) -> None:
        loop = asyncio.get_running_loop()
        while not self.stopping and (left := when - loop.time()) > 0:
            await asyncio.sleep(min(0.25, left))

    async def pause(self, page: Page, seconds: float, reason: str) -> None:
        """Tek sekmede terminalde (ve --watch'ta tarayıcıda) geri sayım; paralelde sessiz bekleme."""
        loop = asyncio.get_running_loop()
        end = loop.time() + seconds
        tty = sys.stdout.isatty() and self.parallel == 1
        while not self.stopping and (left := end - loop.time()) > 0:
            text = f"⏳ {reason} — sonraki profile {math.ceil(left)} sn"
            if tty:
                print(f"\r   {text}   ", end="", flush=True)
            await show_step(page, text, GRAY)
            await asyncio.sleep(min(1.0, left))
        if tty:
            print("\r" + " " * 70 + "\r", end="", flush=True)


async def worker(run: Run, ctx, queue: asyncio.Queue) -> None:
    page = await ctx.new_page()
    fail_limit = max(3, run.parallel + 1)
    try:
        while not run.stopping:
            try:
                n, username, date = queue.get_nowait()
            except asyncio.QueueEmpty:
                break
            await run.take_slot()
            if run.stopping:
                break
            try:
                result = await run.islem.fn(page, username, dry_run=run.args.dry_run,
                                            stopping=lambda: run.stopping)
            except PWError as exc:
                log(f"[{n}/{run.total}] {username}: hata {str(exc).splitlines()[0][:120]}")
                result = "failed"
            if result == "aborted":
                break  # kayda geçmez; sonraki çalıştırmada yeniden denenir
            run.record(n, username, date, result)
            run.maybe_stats()

            if result in STOP_RESULTS:
                await run.stop(result, page, username)
                break
            if run.consecutive_fail >= fail_limit:
                await run.stop("silent", page, username)
                break
            if not run.interval:
                if result == run.islem.done:
                    await run.pause(page, random.uniform(run.args.min_delay, run.args.max_delay),
                                    "Instagram engeli yememek için bekleniyor")
                else:
                    await run.pause(page, random.uniform(1, 2), "atlandı")
    finally:
        try:
            await page.close()
        except PWError:
            pass


async def open_context(pw, account: str, args):
    return await pw.chromium.launch_persistent_context(
        user_data_dir=str(PROFILES_DIR / re.sub(r"\W", "_", account)),
        channel="chrome",
        headless=args.headless,
        slow_mo=300 if args.watch else 0,
        # Ctrl+C'yi script yönetiyor (sekmeler eldeki profili bitirip dursun)
        handle_sigint=False,
        locale="en-US",
        viewport={"width": 1280, "height": 900},
        args=["--disable-blink-features=AutomationControlled"],
    )


async def run_all(run: Run, todo: list[tuple[str, str]]) -> None:
    loop = asyncio.get_running_loop()

    def on_sigint() -> None:
        log("durduruluyor — açık sekmeler eldeki profili bitiriyor (hemen çıkmak için tekrar Ctrl+C)…")
        run.stop_reason = run.stop_reason or "user"
        loop.remove_signal_handler(signal.SIGINT)

    try:
        loop.add_signal_handler(signal.SIGINT, on_sigint)
    except (NotImplementedError, RuntimeError):
        pass

    async with async_playwright() as pw:
        ctx = await open_context(pw, run.account, run.args)
        try:
            first = ctx.pages[0] if ctx.pages else await ctx.new_page()
            if not await ensure_logged_in(first, run.account, run.args.headless):
                run.stop_reason = "logged_out"
                log("HATA: giriş yapılamadı.")
                return

            queue: asyncio.Queue = asyncio.Queue()
            for n, (username, date) in enumerate(todo, 1):
                queue.put_nowait((n, username, date))
            run.started = time.monotonic()
            run.next_slot = loop.time()
            await asyncio.gather(*(worker(run, ctx, queue) for _ in range(run.parallel)))

            if run.stop_reason == "user" and not run.announced:
                await run.stop("user")
            if WATCH and not run.stopping:
                await show_step(first, "Bitti — tarayıcı 6 sn sonra kapanacak", GRAY, 6_000)
        finally:
            save_state(run.state, run.islem.state_path)
            try:
                await ctx.close()
            except PWError:
                pass


