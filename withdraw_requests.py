@dataclass(frozen=True)
class Islem:
    """Geri çekme ve istek atma aynı çalıştırıcıyı kullanır (sekmeler, --hedef-dk,
    engel raporu, kaldığı yerden devam); aradaki farklar burada."""

    name: str  # rate_limit.log'daki "islem"
    fn: Callable[..., Awaitable[str]]  # (page, username, dry_run=, stopping=) -> sonuç
    done: str  # başarı sonucu; state'te bu anahtarın altında tutulur
    verb: str  # "geri çekildi"
    noun: str  # "geri çekilen"
    final_skips: frozenset[str]  # tekrar çalıştırmada yeniden denenmeyecek sonuçlar
    labels: dict[str, str]  # profil başına log satırı
    summary: dict[str, str]  # özet tablosu
    state_file: Path | None  # None: STATE_FILE
    log_key: str  # rate_limit.log'daki sayaç alanı

    @property
    def state_path(self) -> Path:
        # STATE_FILE çağrı anında okunur; testler onu geçici klasöre çeviriyor
        return self.state_file or STATE_FILE


