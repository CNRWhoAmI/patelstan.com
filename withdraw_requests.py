WATCH = False
GRAY, RED, GREEN, AMBER = "#475569", "#e11d48", "#16a34a", "#d97706"


async def show_step(page: Page, text: str, color: str = GRAY, hold_ms: int = 0) -> None:
    """Sayfanın altına adım açıklaması basar (sadece --watch)."""
    if not WATCH:
        return
    try:
        await page.evaluate(
            """([text, color]) => {
                let el = document.getElementById('__geri_cek');
                if (!el) {
                    el = document.createElement('div');
                    el.id = '__geri_cek';
                    document.body.appendChild(el);
                }
                Object.assign(el.style, {
                    position: 'fixed', bottom: '24px', left: '50%',
                    transform: 'translateX(-50%)', zIndex: 2147483647,
                    background: color, color: '#fff', padding: '12px 22px',
                    borderRadius: '12px', font: '600 17px system-ui, sans-serif',
                    boxShadow: '0 8px 28px rgba(0,0,0,.35)', pointerEvents: 'none',
                    maxWidth: '90vw', textAlign: 'center',
                });
                el.textContent = text;
            }""",
            [text, color],
        )
    except PWError:
        pass
    if hold_ms:
        await page.wait_for_timeout(hold_ms)


async def highlight(page: Page, locator, text: str, color: str, hold_ms: int) -> None:
    """Butonun etrafına çerçeve çizer, açıklama basar, izlemen için bekler."""
    if not WATCH:
        return
    try:
        await locator.evaluate(
            "(el, c) => { el.scrollIntoView({block: 'center'});"
            " el.style.outline = `4px solid ${c}`; el.style.outlineOffset = '4px';"
            " el.style.borderRadius = '8px'; }",
            color,
        )
    except PWError:
        pass
    await show_step(page, text, color, hold_ms)


