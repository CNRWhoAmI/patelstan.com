PENDING_NAMES = ("pending_follow_requests.json", "pending_follow_requests.html")
USERNAME_RE = re.compile(r"^[A-Za-z0-9._]{1,30}$")
# Export'un dili hesabın diline göre değişiyor: "Username" / "Kullanıcı adı"
USER_LABEL_RE = re.compile(r"user\s*name|kullan[ıi]c[ıi]\s*ad[ıi]", re.I)
# Başlıktaki sahip: "Generated by x on …" / "… tarihinde x oluşturdu"
OWNER_RES = [
    re.compile(r"generated by\s+@?([A-Za-z0-9._]{1,30})", re.I),
    re.compile(r"@?([A-Za-z0-9._]{1,30})\s+oluşturdu", re.I),
]


def _text(fragment: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", fragment))).strip()


def _clean_username(value: str) -> str:
    value = value.strip().lstrip("@")
    return value if USERNAME_RE.match(value) else ""


def _instagram_username(href: str) -> str:
    """Sadece instagram.com linklerinden okur; bio'daki Spotify/VSCO linkleri değil."""
    m = re.match(r"https?://(?:www\.)?instagram\.com/(?:_u/)?([^/?#]+)", href.strip(), re.I)
    return _clean_username(m.group(1)) if m else ""


def export_owner(path: Path) -> str | None:
    """HTML export'u oluşturan hesap, dosya başlığından."""
    if path.suffix != ".html":
        return None
    try:
        with path.open(encoding="utf-8", errors="ignore") as fh:
            raw = fh.read(200_000)  # başlıktan önce ~14 KB'lık <style> bloğu var
    except OSError:
        return None
    end = raw.find("</header>")
    head = _text(re.sub(r"<style\b.*?</style>", " ", raw[: end if end >= 0 else None], flags=re.S | re.I))
    for pattern in OWNER_RES:
        m = pattern.search(head)
        if m:
            return m.group(1)
    return None


def owner_of(path: Path) -> str | None:
    """Önce dosya başlığı, yoksa instagram-<hesap>-<tarih>-… klasör adı."""
    owner = export_owner(path)
    if owner:
        return owner
    for part in path.parts:
        m = re.match(r"instagram-(.+)-\d{4}-\d{2}-\d{2}-", part)
        if m:
            return m.group(1)
    return None


def find_pending_files() -> list[Path]:
    """downloads/ altındaki tüm listeler, en yeni önce (klasör yapısı fark etmez)."""
    if not DOWNLOADS_DIR.exists():
        return []
    files = [p for p in DOWNLOADS_DIR.rglob("pending_follow_requests.*") if p.name in PENDING_NAMES]
    return sorted(files, key=lambda p: p.stat().st_mtime, reverse=True)


def find_pending_file(account: str) -> Path | None:
    """Bu hesaba ait en yeni liste. Sahibi okunamayan dosya (ör. JSON) sadece
    downloads/<hesap>/ altındaysa sayılır — başka hesabın listesini bu hesabın
    oturumuyla işlememek için. Diğer durumlarda --file ile açıkça verilmeli."""
    folder = re.sub(r"\W", "_", account)
    for path in find_pending_files():
        owner = owner_of(path)
        if owner is not None:
            if owner.lower() == account.lower():
                return path
        elif folder in path.relative_to(DOWNLOADS_DIR).parts:
            return path
    return None


def parse_html(path: Path) -> list[tuple[str, str]]:
    raw = path.read_text(encoding="utf-8")
    body = raw[raw.find("</header>"):] if "</header>" in raw else raw

    # Her istek bir tablo, satırlar [etiket, değer]; tarih tablodan sonraki ilk div.
    # Etiket metnine değil yapıya bakıyoruz ki Türkçe/İngilizce fark etmesin.
    result = []
    for chunk in re.split(r"(?=<table\b)", body):
        table = re.match(r"<table\b.*?</table>", chunk, re.S | re.I)
        if not table:
            continue
        rows = []
        for tr in re.findall(r"<tr\b.*?</tr>", table.group(0), re.S | re.I):
            cells = re.findall(r"<td\b[^>]*>(.*?)</td>", tr, re.S | re.I)
            if cells:
                label = _text(cells[0]) if len(cells) > 1 else ""
                rows.append((label, _text(cells[-1]), re.findall(r'href="([^"]+)"', cells[-1])))

        username = ""
        for label, value, hrefs in rows:
            if USER_LABEL_RE.search(label):
                username = _clean_username(value) or next(filter(None, map(_instagram_username, hrefs)), "")
                break
        if not username:
            # Etiket tanınmadı: instagram linki, yoksa link olmayan son geçerli değer
            for _, value, hrefs in reversed(rows):
                username = next(filter(None, map(_instagram_username, [*hrefs, value])), "")
                if not username and not value.lower().startswith("http"):
                    username = _clean_username(value)
                if username:
                    break
        if not username:
            continue

        date = re.search(r"<div\b[^>]*>([^<]{1,60})</div>", chunk[table.end():])
        result.append((username, html.unescape(date.group(1)).strip() if date else ""))

    if not result:
        # Eski biçim: sadece profil linkleri
        for href in re.findall(r'href="([^"]+)"', body):
            username = _instagram_username(href)
            if username:
                result.append((username, ""))
    return result


def parse_json(path: Path) -> list[tuple[str, str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    items = data.get("relationships_follow_requests_sent", data) if isinstance(data, dict) else data
    result = []
    for item in items:
        sld = (item.get("string_list_data") or [{}])[0]
        username = (
            _clean_username(str(sld.get("value") or ""))
            or _clean_username(str(item.get("title") or ""))
            or _instagram_username(str(sld.get("href") or ""))
        )
        ts = sld.get("timestamp")
        date = datetime.fromtimestamp(ts).strftime("%b %d, %Y %H:%M") if ts else ""
        if username:
            result.append((username, date))
    return result


def load_pending(path: Path) -> list[tuple[str, str]]:
    items = parse_json(path) if path.suffix == ".json" else parse_html(path)
    seen: set[str] = set()
    unique = []
    for username, date in items:
        if username.lower() not in seen:
            seen.add(username.lower())
            unique.append((username, date))
    return unique


