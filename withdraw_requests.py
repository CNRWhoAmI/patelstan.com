async def header_state(page: Page) -> tuple[str, list[str]]:
    """Profil başlığındaki takip butonunun durumu: requested/following/follow/unknown."""
    try:
        texts = [t.strip() for t in await page.locator(HEADER_BUTTONS).all_inner_texts()]
    except PWError:
        return "unknown", []
    texts = [t for t in texts if t][:15]
    for pattern, name in ((REQUESTED_RE, "requested"), (FOLLOWING_RE, "following"), (FOLLOW_RE, "follow")):
        if any(pattern.match(t) for t in texts):
            return name, texts
    return "unknown", texts


async def body_text(page: Page) -> str:
    try:
        return await page.locator("body").inner_text(timeout=2_000)
    except PWError:
        return ""


def url_problem(page: Page) -> str | None:
    if CHALLENGE_URL_RE.search(page.url):
        return "checkpoint"
    if LOGIN_URL_RE.search(page.url):
        return "logged_out"
    return None


async def wait_profile(page: Page, timeout: float = 20.0) -> str:
    """Profil yüklenene kadar bekler (sabit bekleme yerine). "Requested" görülünce
    hemen döner; "Follow"/"Following" ise sayfa yüklenirken geçici görünebildiği
    için 1 sn aynı kalmasını bekler."""
    loop = asyncio.get_running_loop()
    end = loop.time() + timeout
    last, since = None, 0.0
    while loop.time() < end:
        problem = url_problem(page)
        if problem:
            return problem
        state, _ = await header_state(page)
        if state == "requested":
            return state
        if state in ("follow", "following"):
            if state != last:
                last, since = state, loop.time()
            elif loop.time() - since >= 1.0:
                return state
        else:
            last = None
            text = await body_text(page)
            if NOT_FOUND_RE.search(text):
                return "not_found"
            if BLOCKED_RE.search(text):
                return "blocked"
        await asyncio.sleep(0.25)
    return last or "unknown"


async def withdraw_one(page: Page, username: str, dry_run: bool = False, stopping=lambda: False) -> str:
    """
    Dönüş: withdrawn / following / no_request / not_found / failed /
           blocked / checkpoint / logged_out   (dry-run'da: requested)
           aborted — başka sekme engel gördüğü için tıklamadan bırakıldı
    """
    await page.goto(f"https://www.instagram.com/{username}/", wait_until="domcontentloaded", timeout=45_000)
    state = await wait_profile(page)

    if state in STOP_RESULTS:
        return state
    if state == "not_found":
        await show_step(page, f"@{username} — hesap yok, atlanıyor", AMBER, 2_000)
        return "not_found"
    await show_step(page, f"@{username} açıldı — takip butonu kontrol ediliyor…", GRAY, 1_200)
    if state == "following":
        await show_step(page, f"@{username} isteği kabul etmiş (Following) — DOKUNULMUYOR", AMBER, 2_500)
        return "following"
    if state == "follow":
        await show_step(page, f"@{username} için bekleyen istek yok — atlanıyor", AMBER, 2_000)
        return "no_request"
    if state != "requested":
        _, texts = await header_state(page)
        log(f"  {username}: buton tanınmadı {texts}")
        return "failed"
    if dry_run:
        return "requested"
    if stopping():
        return "aborted"

    button = page.locator("header").get_by_role("button", name=REQUESTED_RE).first
    await highlight(page, button, f"@{username} — 'Requested' bulundu → tıklanıyor", RED, 2_000)
    try:
        await button.click(timeout=10_000)
    except PWError:
        await page.locator("header div[role='button']").filter(has_text=REQUESTED_RE).first.click(timeout=10_000)

    # Onay penceresi gelince "Unfollow"a bas (gelmezse bazı sürümler doğrudan iptal ediyor)
    confirm = page.get_by_role("dialog").get_by_role("button", name=CONFIRM_RE).first
    try:
        await confirm.wait_for(state="visible", timeout=5_000)
        await highlight(page, confirm, "Onay penceresi → 'Unfollow' tıklanıyor", RED, 1_800)
        await confirm.click(timeout=10_000)
    except PWTimeout:
        pass

    # Doğrula: buton "Follow"a dönmeli
    for _ in range(40):  # ~10 sn
        await asyncio.sleep(0.25)
        problem = url_problem(page)
        if problem:
            return problem
        if BLOCKED_RE.search(await body_text(page)):
            return "blocked"
        state, _ = await header_state(page)
        if state == "follow":
            follow_btn = page.locator("header").get_by_role("button", name=FOLLOW_RE).first
            await highlight(page, follow_btn, f"✓ @{username} — istek geri çekildi (buton artık 'Follow')", GREEN, 2_500)
            return "withdrawn"
    return "failed"


async def is_logged_out(page: Page) -> bool:
    if LOGIN_URL_RE.search(page.url):
        return True
    try:
        return await page.locator("input[name='username'], input[name='email']").count() > 0
    except PWError:
        return False


async def ensure_logged_in(page: Page, account: str, headless: bool) -> bool:
    await page.goto("https://www.instagram.com/", wait_until="domcontentloaded", timeout=60_000)
    await page.wait_for_timeout(3_000)
    if CHALLENGE_URL_RE.search(page.url):
        log("Instagram doğrulama istiyor — --headless olmadan çalıştırıp tarayıcıda tamamla.")
        return False
    if not await is_logged_out(page):
        return True
    if headless:
        log("oturum kapalı — bir kez --headless olmadan çalıştırıp giriş yap.")
        return False

    password = getpass(f"{account} şifresi: ") if sys.stdin.isatty() else None
    await page.goto(LOGIN_URL, wait_until="domcontentloaded", timeout=60_000)
    if password:
        try:
            await page.fill("input[name='username']", account, timeout=20_000)
            await page.fill("input[name='password']", password, timeout=20_000)
            await page.press("input[name='password']", "Enter")
        except PWError as exc:
            log(f"login formu doldurulamadı: {exc}")
    log("2FA veya doğrulama varsa tarayıcıda tamamla — 3 dk bekleniyor…")
    for _ in range(60):
        await page.wait_for_timeout(3_000)
        if not await is_logged_out(page) and not CHALLENGE_URL_RE.search(page.url):
            log("giriş başarılı.")
            return True
    return False


