def load_state(path: Path | None = None) -> dict:
    path = path or STATE_FILE
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {}


def save_state(state: dict, path: Path | None = None) -> None:
    (path or STATE_FILE).write_text(json.dumps(state, indent=2, ensure_ascii=False), encoding="utf-8")


def append_rate_log(run: Run) -> None:
    """Her çalıştırmanın sonucu — farklı hızlarda ne zaman engel geldiğini karşılaştırmak için."""
    elapsed = time.monotonic() - run.started
    entry = {
        "zaman": datetime.now().isoformat(timespec="seconds"),
        "hesap": run.account,
        "islem": run.islem.name,
        "sonuc": run.stop_reason or "tamamlandi",
        "sekme": run.parallel,
        "hedef_dk": run.args.hedef_dk,
        "bekleme_sn": None if run.interval else [run.args.min_delay, run.args.max_delay],
        "islenen": run.processed,
        run.islem.log_key: run.succeeded,
        "sure_sn": round(elapsed),
        "hiz_profil_dk": round(run.rate_per_min(), 1),
    }
    try:
        LOG_DIR.mkdir(exist_ok=True)
        with RATE_LOG.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(entry, ensure_ascii=False) + "\n")
    except OSError:
        pass


def plan_speed(args: argparse.Namespace, count: int) -> tuple[int, float | None]:
    """Sekme sayısı ve (--hedef-dk varsa) profiller arası ortak aralık; tahmini terminale yazar."""
    per_item = PER_ITEM_SEC_WATCH if args.watch else PER_ITEM_SEC
    interval = None
    if args.hedef_dk:
        interval = args.hedef_dk * 60 / count
        parallel = args.parallel or min(10, max(1, math.ceil(per_item / interval) + 1))
    else:
        parallel = args.parallel or 1
    if args.watch and parallel > 1:
        log("--watch tek sekmede izlenebiliyor; sekme sayısı 1'e indirildi.")
        parallel = 1
    parallel = max(1, min(parallel, count))

    if interval:
        reachable = parallel / per_item * 60  # profil/dk
        wanted = 60 / interval
        log(
            f"hedef ~{args.hedef_dk:g} dk: {parallel} sekme, ~{interval:.1f} sn'de bir profil "
            f"(~{wanted:.0f} profil/dk)"
        )
        if reachable < wanted * 0.9:
            minutes = count / reachable
            log(f"UYARI: {parallel} sekmeyle bu hıza yetişilemez; tahmini süre ~{fmt_duration(minutes * 60)}.")
    else:
        avg = per_item + (args.min_delay + args.max_delay) / 2
        log(f"{parallel} sekme, tahmini süre ~{fmt_duration(count * avg / parallel)}.")
    if not args.dry_run and count > 150:
        log("Uzun liste: Instagram bir noktada engel koyabilir. Olursa bütün sekmeler durur, "
            "terminale ne zaman geldiği yazılır; aynı komut kaldığı yerden devam eder.")
    log("Ctrl+C ile durdurabilirsin (ilerleme kaydedilir).")
    return parallel, interval


def execute(run: Run, todo: list[tuple[str, str]], list_size: int) -> int:
    """Çalıştırır, ilerlemeyi ve hız kaydını yazar, özeti basar; çıkış kodunu döner."""
    args, islem = run.args, run.islem
    try:
        asyncio.run(run_all(run, todo))
    except KeyboardInterrupt:
        run.stop_reason = run.stop_reason or "user"
        log("hemen durduruldu.")
    finally:
        if not args.dry_run:
            save_state(run.state, islem.state_path)
            append_rate_log(run)

    elapsed = time.monotonic() - run.started
    print("\n" + "=" * 64)
    print("ÖZET" + (" (dry-run, hiçbir şey değişmedi)" if args.dry_run else ""))
    print("=" * 64)
    for key, value in sorted(run.counts.items(), key=lambda kv: -kv[1]):
        print(f"  {islem.summary.get(key, key):<34} {value}")
    print(f"\n  süre: {fmt_duration(elapsed)} · hız: {run.rate_per_min():.1f} profil/dk · {run.parallel} sekme")
    if run.stop_reason and run.stop_reason != "user":
        print(f"  durma sebebi: {STOP_TITLES.get(run.stop_reason, run.stop_reason)}")
    if not args.dry_run:
        print(f"  Toplam {islem.noun} (tüm çalıştırmalar): {len(run.acc_state[islem.done])}/{list_size}")
        print(f"  Hız kaydı: {rel(RATE_LOG)}")
    return 1 if run.stop_reason in STOP_RESULTS | {"silent"} else 0


def pick_account(given: str | None) -> str:
    if given:
        return given.lstrip("@")
    # downloads/ altındaki listelerin sahipleri; tek hesap varsa sormadan onu seç
    owners = list(dict.fromkeys(o for p in find_pending_files() if (o := owner_of(p))))
    if len(owners) == 1:
        return owners[0]
    if not sys.stdin.isatty():
        hint = f" Bulunan listeler: {', '.join(owners)}" if owners else ""
        sys.exit(f"HATA: hangi hesap? --account ile ver.{hint}")
    if owners:
        print(f"downloads/ altında birden fazla hesabın listesi var: {', '.join(owners)}")
    return input("Kullanıcı adı: ").strip().lstrip("@")


def main() -> int:
    ap = argparse.ArgumentParser(description="Bekleyen takip isteklerini geri çek")
    ap.add_argument("--account", help="kullanıcı adı (tek hesap varsa otomatik)")
    ap.add_argument("--file", help="pending_follow_requests.html/json yolu (varsayılan: en yeni export)")
    ap.add_argument("--dry-run", action="store_true", help="tıklama, sadece durumları göster")
    ap.add_argument("--limit", type=int, help="en fazla bu kadar işlem yap")
    ap.add_argument("--min-delay", type=float, default=4, help="işlemler arası min bekleme (sn)")
    ap.add_argument("--max-delay", type=float, default=6, help="işlemler arası max bekleme (sn)")
    ap.add_argument("--hedef-dk", type=float, help="listeyi yaklaşık bu kadar dakikada bitir (sekme sayısı otomatik)")
    ap.add_argument("--parallel", type=int, help="aynı anda kaç sekme (varsayılan 1; --hedef-dk ile otomatik)")
    ap.add_argument("--newest-first", action="store_true", help="en yeni istekten başla")
    ap.add_argument("--headless", action="store_true", help="tarayıcıyı gösterme")
    ap.add_argument("--watch", action="store_true", help="izleme modu: yavaş, butonları işaretler")
    args = ap.parse_args()

    global WATCH
    if args.watch:
        WATCH = True
        args.headless = False

    account = pick_account(args.account)
    source = Path(args.file).expanduser().resolve() if args.file else find_pending_file(account)
    if not source or not source.exists():
        files = find_pending_files()
        others = sorted({o for p in files if (o := owner_of(p))} - {account})
        unknown = [p for p in files if owner_of(p) is None]
        hint = ""
        if others:
            hint += f"\ndownloads/ altındaki listeler şu hesaplara ait: {', '.join(others)}."
        if unknown:
            hint += (
                f"\nSahibi okunamayan liste var: {unknown[0].relative_to(ROOT)} — "
                f"bu hesabınsa: ./geri_cek.sh --account {account} --file {unknown[0].relative_to(ROOT)}"
            )
        if not hint:
            hint = "\nExport zip'ini aç, içindeki pending_follow_requests dosyasını downloads/ altına koy."
        sys.exit(f"HATA: @{account} için pending_follow_requests dosyası bulunamadı.{hint}")

    # Bir hesabın listesini öbür hesabın oturumuyla işlememek için
    owner = owner_of(source)
    if owner and owner.lower() != account.lower():
        sys.exit(
            f"HATA: {source.name} @{owner} hesabına ait ama @{account} seçildi.\n"
            f"Doğru hesapla çalıştır:  ./geri_cek.sh --account {owner}"
        )

    pending = load_pending(source)
    if not pending:
        sys.exit(f"HATA: {source} içinde bekleyen istek bulunamadı; dosya biçimi tanınmadı.")
    log(f"hesap: @{account}" + ("" if owner else " (dosyanın sahibi okunamadı, doğru hesap olduğundan emin ol)"))
    if not args.newest_first:
        pending.reverse()  # dosya en yeniden eskiye sıralı; eskiden başla

    state = load_state(GERI_CEK.state_path)
    acc_state = state.setdefault(account, {"withdrawn": {}, "skipped": {}})
    todo = [
        (u, d) for u, d in pending
        if u not in acc_state["withdrawn"] and acc_state["skipped"].get(u) not in FINAL_SKIPS
    ]

    log(f"kaynak: {rel(source)}")
    log(f"{len(pending)} bekleyen istek, {len(pending) - len(todo)} önceden halledilmiş, {len(todo)} kaldı.")
    if args.limit:
        todo = todo[: args.limit]
    if not todo:
        log("yapılacak bir şey yok.")
        return 0

    parallel, interval = plan_speed(args, len(todo))
    run = Run(args=args, account=account, total=len(todo), state=state, acc_state=acc_state,
              islem=GERI_CEK, parallel=parallel, interval=interval)
    return execute(run, todo, len(pending))

if __name__ == "__main__":
    sys.exit(main())
